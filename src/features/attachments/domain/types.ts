import type { ActivityEntry } from "@/features/activity/domain/types";
export interface Attachment {
  id: string;
  projectId: string;
  taskId: string;
  uploaderId: string;
  name: string;
  contentType: string;
  size: number;
  storageKey: string;
  createdAt: Date;
}

export interface AttachmentView extends Attachment {
  uploaderName: string;
}

export interface AttachmentRepository {
  /** Row changes store their audit entries in the same atomic batch. */
  insert(attachment: Attachment, activity: ActivityEntry[]): Promise<void>;
  findById(projectId: string, id: string): Promise<Attachment | undefined>;
  listForTask(projectId: string, taskId: string): Promise<AttachmentView[]>;
  delete(id: string, activity: ActivityEntry[]): Promise<void>;
}

/**
 * Port for file bytes. R2 backs it on Cloudflare, a local folder in dev and E2E, memory in tests.
 * Keys are generated by the service, never taken from the client.
 */
export interface AttachmentStorage {
  put(key: string, data: ArrayBuffer, contentType: string): Promise<void>;
  /** The object's bytes, or null if no object has that key. */
  get(key: string): Promise<ReadableStream<Uint8Array> | null>;
  delete(key: string): Promise<void>;
}

/** An uploaded file as the route hands it over, before validation. */
export interface UploadInput {
  name: string;
  contentType: string;
  data: ArrayBuffer;
}
